package io.mobshield.gradle

import io.mobshield.gradle.internal.CryptoUtils
import java.io.File

data class BuildInfoRequest(
    val expectedSigningCertSha256: String,
    val expectedPackageName: String,
    val expectedInstallers: List<String>,
    val aggressive: Boolean,
    val randomSeedHex: String?,
    val nativeLibraries: List<String>,
    /** Written as MOBSHIELD_VERSION, which `MobShield.getVersion()` returns. */
    val libraryVersion: String = BuildInfoGenerator.LIBRARY_VERSION,
)

data class BuildInfoResult(
    val seedHex: String,
    val buildId: String,
    val headerContent: String,
    val inputsFingerprint: String,
)

/**
 * Generates `mobshield_buildinfo.h` for MobShield's native code when it is compiled from source in
 * the app's build.
 *
 * The header holds no secrets. MOBSHIELD_BUILD_ID is a public identifier that appears in reports and
 * logs and is readable in the binary. Anything an app ships can be read by an attacker, so nothing
 * that is meant to be secret may be generated here.
 */
object BuildInfoGenerator {
    private const val BUILD_ID_BYTES = 8
    private val VERSION_PATTERN = Regex("[0-9A-Za-z][0-9A-Za-z.+-]*")

    /**
     * This plugin's own version, which matches the MobShield sources it is built with. Read from the
     * jar manifest; falls back to 0.0.0-SNAPSHOT when the plugin runs from classes (tests, IDE).
     */
    val LIBRARY_VERSION: String =
        BuildInfoGenerator::class.java.`package`?.implementationVersion ?: "0.0.0-SNAPSHOT"

    fun generate(request: BuildInfoRequest): BuildInfoResult {
        val seed = resolveSeed(request.randomSeedHex)
        val buildId = "android-" + CryptoUtils.deriveBytes(seed, "mobshield-build-id-v1", BUILD_ID_BYTES).toHex()
        val signer = CryptoUtils.normalizeSha256(request.expectedSigningCertSha256)
        require(VERSION_PATTERN.matches(request.libraryVersion)) {
            "libraryVersion must be a plain version string, got \"${request.libraryVersion}\""
        }
        val header = buildString {
            appendLine("/* Generated by io.mobshield.personalize. Contains no secrets; MOBSHIELD_BUILD_ID is public. */")
            appendLine("#ifndef MOBSHIELD_BUILDINFO_H")
            appendLine("#define MOBSHIELD_BUILDINFO_H")
            appendLine()
            appendLine("#define MOBSHIELD_VERSION \"${request.libraryVersion}\"")
            appendLine("#define MOBSHIELD_BUILD_ID \"$buildId\"")
            appendLine("#define MOBSHIELD_SELF_CHECK_MAGIC 0x4D534844u")
            appendLine("#define MOBSHIELD_EXPECTED_SIGNER_SHA256 \"$signer\"")
            appendLine("#define MOBSHIELD_EXPECTED_PACKAGE \"${request.expectedPackageName}\"")
            appendLine("#define MOBSHIELD_AGGRESSIVE_ANTI_DEBUG ${if (request.aggressive) 1 else 0}")
            appendLine()
            appendLine("#endif  // MOBSHIELD_BUILDINFO_H")
        }

        val fingerprint = listOf(
            seed.toHex(),
            signer,
            request.expectedPackageName,
            request.expectedInstallers.joinToString(","),
            request.aggressive.toString(),
            request.nativeLibraries.joinToString(","),
        ).joinToString("|")

        return BuildInfoResult(
            seedHex = seed.toHex(),
            buildId = buildId,
            headerContent = header,
            inputsFingerprint = fingerprint,
        )
    }

    fun shouldSkipGeneration(inputsFile: File, headerFile: File, fingerprint: String): Boolean {
        if (!inputsFile.exists() || !headerFile.exists()) {
            return false
        }
        return inputsFile.readText() == fingerprint
    }

    private fun resolveSeed(randomSeedHex: String?): ByteArray {
        if (!randomSeedHex.isNullOrBlank()) {
            val normalized = CryptoUtils.normalizeSha256(randomSeedHex)
            require(normalized.length == 64) { "randomSeed must be 64 hex characters (256 bits)" }
            return normalized.chunked(2).map { it.toInt(16).toByte() }.toByteArray()
        }
        return CryptoUtils.randomBytes(32)
    }

    private fun ByteArray.toHex(): String = joinToString("") { "%02x".format(it) }

}
